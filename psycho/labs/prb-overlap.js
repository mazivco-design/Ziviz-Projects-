/* Lab: חפיפה — פס של אנשים, קבוצה א' קבועה מימין, קבוצה ב' נגררת; ארבע המשבצות מתעדכנות. */
(function () {
  const { G } = Lab;
  const BX0 = 40, BX1 = 580, BY = 128, BH = 46;
  const pick = (right, hints) => (L, e) => e.type !== "choice" ? null : e.j === right ? true : (hints[e.j] || "נסה שוב.");
  const mk = o => Object.assign({ N: 20, A: 12, B: 7, s: 12, la: "מנגנים", lb: "שרים", groups: false }, o);
  const u = S => (BX1 - BX0) / S.N;
  // cell i counted from the right: A = [0,A), B = [s, s+B)
  function counts(S) {
    let oa = 0, both = 0, ob = 0, nn = 0;
    for (let i = 0; i < S.N; i++) { const a = i < S.A, b = i >= S.s && i < S.s + S.B; if (a && b) both++; else if (a) oa++; else if (b) ob++; else nn++; }
    return { oa, both, ob, nn };
  }
  const BOX = [["רק ", "oa", "fsoft"], ["גם וגם", "both", "fa"], ["רק ", "ob", "fblue-soft"], ["לא ולא", "nn", "box"]];

  function draw(L) {
    const S = L.state, w = u(S), c = counts(S); let h = "";
    // cells
    for (let i = 0; i < S.N; i++) {
      const a = i < S.A, b = i >= S.s && i < S.s + S.B, x = BX1 - (i + 1) * w;
      h += G.rect(x, BY, w, BH, a && b ? "fa" : a ? "fsoft" : b ? "fblue-soft" : "box", { style: "stroke:none" });
    }
    for (let i = 1; i < S.N; i++) { const x = BX1 - i * w; h += G.line(x, BY, x, BY + BH, "mut", { opacity: .35 }); }
    h += G.rect(BX0, BY, BX1 - BX0, BH, "ink");
    h += G.t(BX0 - 6, BY + 29, S.N, "b", "end");
    // A bracket (top, fixed)
    const ax = BX1 - S.A * w;
    h += G.line(ax, BY - 16, BX1, BY - 16, "sa") + G.line(ax, BY - 16, ax, BY - 6, "sa") + G.line(BX1, BY - 16, BX1, BY - 6, "sa");
    h += G.he((ax + BX1) / 2, BY - 26, S.la + ": " + S.A, "a");
    // B bracket (bottom, draggable)
    const bx1 = BX1 - S.s * w, bx0 = BX1 - (S.s + S.B) * w, by = BY + BH + 16, cx = (bx0 + bx1) / 2;
    h += G.line(bx0, by, bx1, by, "sblue") + G.line(bx0, by, bx0, by - 10, "sblue") + G.line(bx1, by, bx1, by - 10, "sblue");
    h += G.he(cx, by + 44, S.lb + ": " + S.B, "blue");
    h += G.knob(cx, by + 2, "B", 15);
    // four boxes (right to left)
    const bw = 124, gap = 8, y0 = 262;
    BOX.forEach(([lab, k, cls], j) => {
      const x = BX1 - 18 - (j + 1) * bw - j * gap, name = k === "oa" ? lab + S.la : k === "ob" ? lab + S.lb : lab;
      h += G.rect(x, y0, bw, 60, cls, { rx: 8 });
      h += G.he(x + bw / 2, y0 + 22, name, k === "both" ? "inv" : "m");
      h += G.t(x + bw / 2, y0 + 50, c[k], k === "both" ? "inv big" : "big");
    });
    if (S.groups) {
      const xr = BX1 - 18, xm = BX1 - 18 - 2 * bw - gap - gap / 2, xl = BX1 - 18 - 4 * bw - 3 * gap, yb = y0 + 68;
      h += G.line(xm + 4, yb, xr, yb, "sa") + G.he((xm + xr) / 2, yb + 22, "כל ה" + S.la + ": " + S.A, "a");
      h += G.line(xl, yb, xm - 4, yb, "ink") + G.he((xl + xm) / 2, yb + 22, "לא " + S.la + (S.groupsN ? ": " + (S.N - S.A) : ": ?"), "b");
    }
    return h;
  }
  function drag(L, key, pt) {
    const S = L.state; if (key !== "B" || S.lock) return;
    S.s = Math.max(0, Math.min(S.N - S.B, Math.round((BX1 - pt.x) / u(S) - S.B / 2)));
  }
  function dragFrom(L, pt) {
    const S = L.state, w = u(S), bx1 = BX1 - S.s * w, bx0 = BX1 - (S.s + S.B) * w;
    return pt.y > BY && pt.y < BY + BH + 40 && pt.x > bx0 - 10 && pt.x < bx1 + 10 ? "B" : null;
  }
  const C = L => counts(L.state);
  const setS = s => L => { L.state.s = s; L.act({ type: "drop", key: "B" }); };

  Lab.register({
    id: "prb-overlap", title: "המחשה: חפיפה", viewBox: "0 0 620 360",
    chapters: ["ארבע המשבצות", "חפיפה מדויקת", "החפיפה הגדולה", "החפיפה הקטנה", "שאלת מבחן"],
    draw, drag, dragFrom,
    steps: [
      // ---- ch0
      { ch: 0, setup: L => { L.state = mk({}); },
        say: "במקהלה 20 חברים, וכל משבצת בפס היא אדם אחד. 12 מנגנים (הסוגר הוורוד למעלה) ו־7 שרים (הסוגר הכחול למטה). את השרים אפשר להזיז.",
        task: "גרור את הסוגר הכחול כך ש־3 חברים בדיוק גם מנגנים וגם שרים.",
        demo: setS(9),
        check: (L, e) => { if (e.type !== "drop") return null; const b = C(L).both; return b === 3 ? true : b > 3 ? `עכשיו ${b} עושים גם וגם. הזז את השרים שמאלה, החוצה מהמנגנים.` : `עכשיו ${b} עושים גם וגם. הזז את השרים ימינה, לתוך המנגנים.`; },
        ok: "קרא את ארבע המשבצות מימין לשמאל: רק מנגנים 9, גם וגם 3, רק שרים 4, לא ולא 4. ביחד 20. זו <b>שיטת הריבועים</b> של הקורס." },
      { ch: 0, setup: L => { L.state.groups = true; L.state.lock = true; },
        say: "שתי המשבצות הימניות הן כל המנגנים: 9 + 3 = 12. שתי השמאליות הן כל מי ש<b>לא</b> מנגן.",
        task: "כמה חברים לא מנגנים?", choices: ["4", "8", "9", "11"],
        check: pick(1, { 0: "4 זה רק 'לא ולא'. גם מי שרק שר לא מנגן.", 2: "9 הם אלה שרק מנגנים.", 3: "חיסרת רק את 'רק מנגנים'. גם 3 של 'גם וגם' מנגנים." }),
        ok: L => { L.state.groupsN = true; L.render(); return "4 + 4 = 8, וזה בדיוק 20 − 12."; } },
      { ch: 0, setup: L => { L.state.groups = false; },
        say: "ומי ששר? הוא נמצא בשתי המשבצות האמצעיות.",
        task: "כמה חברים שרים?", choices: ["3", "4", "7", "11"],
        check: pick(2, { 0: "3 הם רק 'גם וגם'. גם מי שרק שר, שר.", 1: "4 הם רק מי ש<b>רק</b> שר. גם 3 של 'גם וגם' שרים.", 3: "11 = 20 − 9. אבל השרים הם שתי המשבצות האמצעיות." }),
        ok: "3 + 4 = 7, בדיוק הנתון. המלכודת: לבלבל בין 'רק שרים' (4) לבין 'שרים' (7)." },
      // ---- ch1
      { ch: 1, setup: L => { L.state = mk({ N: 40, A: 24, B: 22, s: 18, la: "קפה", lb: "תה" }); },
        say: "במשרד 40 עובדים. 24 שותים קפה, 22 שותים תה, ו־6 לא שותים אף אחד מהם. כמה שותים את שניהם?",
        task: "הזז את שותי התה כך שבמשבצת 'לא ולא' יהיו בדיוק 6.",
        demo: setS(12),
        check: (L, e) => { if (e.type !== "drop") return null; const n = C(L).nn; return n === 6 ? true : n < 6 ? `ב'לא ולא' יש עכשיו ${n}. צריך לפנות מקום בצד שמאל: הזז את התה ימינה.` : `ב'לא ולא' יש עכשיו ${n}. הזז את התה שמאלה.`; },
        ok: "נוצרה חפיפה של <b>12</b>. בדיקה: 12 + 12 + 10 + 6 = 40." },
      { ch: 1, setup: L => { L.state.lock = true; },
        say: "חשבון בלי פס: מי ששותה משהו הוא 40 − 6 = 34 עובדים. אבל 24 + 22 = 46.",
        task: "למה 46 יותר מ־34?", choices: ["כי מי ששותה גם וגם נספר פעמיים", "כי 6 עובדים לא שותים כלום", "יש טעות בנתונים"],
        check: pick(0, { 1: "את ה־6 כבר הורדנו. הם לא בתוך 24 או 22.", 2: "הנתונים תקינים. מה ספרנו פעמיים כשחיברנו 24 + 22?" }),
        ok: "העודף 46 − 34 = 12 הוא בדיוק החפיפה. הנוסחה: <b>סה״כ = א' + ב' − גם וגם + לא ולא</b>." },
      { ch: 1,
        say: "שאלה חשובה לפני שממשיכים.",
        task: "ואם לא היו מספרים לנו כמה לא שותים כלום?", choices: ["החפיפה עדיין 12", "החפיפה הייתה 0", "יש כמה אפשרויות, וצריך טווח"],
        check: pick(2, { 0: "בלי 'לא ולא' הסוגר הכחול חופשי לזוז. האם החפיפה נשארת קבועה?", 1: "למה דווקא 0? הסוגר הכחול חופשי לזוז." }),
        ok: "בדיוק. בלי הנתון הזה הסוגר זז, והחפיפה משתנה. זו <b>שאלת טווחים</b>." },
      // ---- ch2
      { ch: 2, setup: L => { L.state = mk({ N: 40, A: 24, B: 22, s: 9, la: "קפה", lb: "תה" }); },
        say: "אותו משרד, בלי הנתון של 'לא ולא'. 'לכל היותר' שואל על המקסימום.",
        task: "גרור את התה למקום שבו החפיפה <b>הכי גדולה</b> שאפשר.",
        demo: setS(0),
        check: (L, e) => { if (e.type !== "drop") return null; return C(L).both === 22 ? true : "אפשר עוד: הזז את התה ימינה, עמוק יותר לתוך הקפה."; },
        ok: "כל 22 שותי התה נמצאים בתוך שותי הקפה. <b>חפיפה מקסימלית = הקבוצה הקטנה</b>. יותר מזה אי אפשר, כי אין יותר שותי תה." },
      { ch: 2,
        say: "בדיקה מהירה, בלי פס.",
        task: "בכיתה 32 תלמידים: 20 לומדים ספרדית ו־9 לומדים ערבית. לכל היותר, כמה לומדים את שתיהן?", choices: ["0", "9", "20", "29"],
        check: pick(1, { 0: "0 הוא דווקא המינימום כאן. השאלה על המקסימום.", 2: "רק 9 לומדים ערבית. איך 20 ילמדו את שתיהן?", 3: "זה סכום הקבוצות. החפיפה לא יכולה להיות גדולה מהקבוצה הקטנה." }),
        ok: "9: כל לומדי הערבית לומדים גם ספרדית. הקבוצה הקטנה כולה בתוך הגדולה." },
      // ---- ch3
      { ch: 3, setup: L => { L.state = mk({ N: 40, A: 24, B: 22, s: 6, la: "קפה", lb: "תה" }); },
        say: "ועכשיו הכיוון ההפוך. 'לכל הפחות' שואל על המינימום: כמה <b>חייבים</b> לחפוף.",
        task: "גרור את התה למקום שבו החפיפה <b>הכי קטנה</b>.",
        demo: setS(18),
        check: (L, e) => { if (e.type !== "drop") return null; return C(L).both === 6 ? true : "התה עוד יכול לזוז שמאלה. יש שם מקום פנוי."; },
        ok: "התה נתקע בקצה ואין לו לאן לברוח. 24 + 22 = 46, ויש רק 40 מקומות, ולכן 6 חייבים לחפוף. <b>חפיפה מינימלית = א' + ב' − סה״כ</b>." },
      { ch: 3, setup: L => { L.state = mk({ N: 40, A: 15, B: 20, s: 0, la: "שחייה", lb: "ריצה" }); L.state.lock = true; },
        say: "קבוצות אחרות: מתוך 40 ילדים, 15 בחוג שחייה ו־20 בחוג ריצה.",
        task: "לפני שגוררים: מה החפיפה המינימלית?", choices: ["−5", "0", "5", "15"],
        check: pick(1, { 0: "חפיפה היא מספר אנשים. היא לא יכולה להיות שלילית.", 2: "15 + 20 = 35, פחות מ־40. האם הקבוצות בכלל חייבות לחפוף?", 3: "15 זה המקסימום, הקבוצה הקטנה. השאלה על המינימום." }),
        ok: "15 + 20 = 35 לא עובר את 40, ולכן אפשר להפריד ביניהן לגמרי. בדוק בעצמך." },
      { ch: 3, setup: L => { L.state.lock = false; },
        say: "הפס פתוח.",
        task: "גרור את הריצה כך שלא תהיה חפיפה בכלל.",
        demo: setS(18),
        check: (L, e) => { if (e.type !== "drop") return null; const b = C(L).both; return b === 0 ? true : `עדיין ${b} בחפיפה. הזז את הריצה שמאלה, החוצה מהשחייה.`; },
        ok: "אפס חפיפה, ועדיין נשארו אנשים ב'לא ולא'. כשהקבוצות יחד לא עוברות את הסך הכול, <b>המינימום הוא 0</b>." },
      // ---- ch4
      { ch: 4, setup: L => { L.state = mk({ N: 60, A: 45, B: 38, s: 0, la: "מוזיאון", lb: "חוף" }); },
        say: "שאלה ברמת מבחן. הפס פתוח לשימוש חופשי.",
        task: "בקבוצה של 60 תיירים, 45 ביקרו במוזיאון ו־38 ביקרו בחוף. לכל הפחות, כמה תיירים ביקרו בשני המקומות?",
        choices: ["7", "15", "23", "38"],
        check: pick(2, { 0: "45 − 38 לא קשור לחפיפה. גרור את החוף הכי שמאלה שאפשר ובדוק.", 1: "15 = 60 − 45, כמה לא ביקרו במוזיאון. מה קורה כשהחוף נדחק לקצה?", 3: "38 זה המקסימום. 'לכל הפחות' שואל על המינימום." }),
        ok: L => { L.state.s = 22; L.render(); return "45 + 38 = 83, ויש רק 60 תיירים. לכן 83 − 60 = <b>23</b> חייבים לבקר בשני המקומות."; } },
      { ch: 4,
        say: "<b>סיכום ההמחשה:</b><br>1. ארבע משבצות מימין לשמאל: רק א' | גם וגם | רק ב' | לא ולא. 'א'' = שתי הימניות, 'ב'' = שתי האמצעיות.<br>2. חפיפה מדויקת: סה״כ = א' + ב' − גם וגם + לא ולא.<br>3. לכל היותר: החפיפה = הקבוצה הקטנה.<br>4. לכל הפחות: א' + ב' − סה״כ, ואם יוצא שלילי, 0.", next: "סיום ההמחשה" },
    ],
  });
})();
